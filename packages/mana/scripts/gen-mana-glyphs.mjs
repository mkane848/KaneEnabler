#!/usr/bin/env node
/**
 * Regenerates src/glyphs.ts from the mana-font SVG sources.
 *
 * Usage:
 *   pnpm --filter @mtg/mana run gen-glyphs
 *
 * mana-font is a devDependency purely so this script has a pinned, verifiable
 * copy of the artwork to read — none of it ships. The app bundles the emitted
 * path data instead, which is why there's no webfont request at runtime.
 *
 * Run this only when adding a symbol to KEYS or bumping mana-font.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SVG_DIR = path.join(ROOT, 'node_modules', 'mana-font', 'svg');
const OUT_PATH = path.join(ROOT, 'src', 'glyphs.ts');

// Only symbols that can appear in a mana cost. Tap, untap, and energy are
// ability-cost and resource symbols — they never show up in mana_cost, so
// carrying their paths would be dead weight.
const KEYS = ['w', 'u', 'b', 'r', 'g', 'c', 's', 'p'];

const HEADER = `/**
 * Mana symbol glyphs, inlined.
 *
 * Generated from the mana-font package (MIT, Andrew Gioia) as raw path data
 * rather than loaded as a webfont. The font's stylesheet offers no woff2, so
 * browsers would download a ~408KB .woff to render a handful of pips — and
 * loading it from a CDN put a third-party request on the critical path of an
 * app that is otherwise entirely offline.
 *
 * Each path is the glyph only; the coloured disc behind it is CSS, which is
 * also how the original font works.
 *
 * Generated by scripts/gen-mana-glyphs.mjs — edit that, not this.
 */

/** Glyph path data, on a 32x32 viewBox. */
export const MANA_GLYPHS: Record<string, string> = {
`;

async function readGlyph(key) {
  let svg;
  try {
    svg = await readFile(path.join(SVG_DIR, `${key}.svg`), 'utf8');
  } catch {
    throw new Error(`Could not read ${key}.svg — is mana-font installed? Try: npm install`);
  }

  // The renderer hardcodes a 32x32 viewBox and draws exactly one path, so a
  // glyph that breaks either assumption has to fail loudly here rather than
  // render subtly wrong (mana-font's energy symbol, for one, is 27x32).
  const viewBox = svg.match(/viewBox="([^"]*)"/)?.[1];
  if (viewBox !== '0 0 32 32') {
    throw new Error(`${key}.svg has viewBox "${viewBox}", expected "0 0 32 32"`);
  }

  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]*)"/g)].map((m) => m[1]);
  if (paths.length !== 1) {
    throw new Error(`${key}.svg has ${paths.length} paths; the renderer draws one`);
  }
  if (paths[0].includes("'")) {
    throw new Error(`${key}.svg path contains a quote and would break the emitted literal`);
  }

  return paths[0];
}

const rows = [];
for (const key of KEYS) {
  rows.push(`  ${key}: '${await readGlyph(key)}',`);
}

await writeFile(
  OUT_PATH,
  HEADER + rows.join('\n') + "\n};\n\nexport const MANA_VIEWBOX = '0 0 32 32';\n",
  'utf8',
);
console.log(`Wrote ${KEYS.length} glyphs to ${path.relative(ROOT, OUT_PATH)}`);
